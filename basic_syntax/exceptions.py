# 1. Базовый try-except
# Код в блоке try пробует выполниться
# Если вылетает ошибка, программа не падает, а идет в except
a = 10
b = 0

try:
    res = a / b
    print('Результат:', res)
except ZeroDivisionError:
    print('Ошибка: делить на ноль нельзя')


# 2. Получение текста ошибки через as
# as err сохраняет саму ошибку в переменную, чтобы посмотреть причину
val = 'abc'

try:
    num = int(val)
except ValueError as err:
    print('Не вышло перевести в число:', err)


# 3. Несколько блоков except под разные ошибки
# Python проверяет их сверху вниз и заходит в первый подходящий
items = [1, 2, 3]

try:
    # Ошибка индекса - элемента с номером 10 нет
    x = items[10]
    y = items[0]/5
except IndexError:
    print('Элемент с таким номером не найден')
except ZeroDivisionError:
    print('Ошибка: делить на ноль нельзя')


# 4. Блок else
# Срабатывает только если в try не возникло никаких ошибок
x = 20
y = 4

try:
    res = x / y
except ZeroDivisionError:
    print('Деление на ноль')
else:
    print('Все посчитано без ошибок:', res)


# 5. Блок finally
# Выполняется всегда была ошибка или нет
# Часто нужен, чтобы закрыть файл или завершить работу
try:
    total = 5 + 5
    print('Сумма:', total)
except TypeError:
    print('Складывать можно только одинаковые типы')
finally:
    print('Этот блок сработал в любом случае')


# 6. Ручной вызов ошибки через raise
# Нужен, когда мы сами хотим остановить код при некорректных данных
age = -5

try:
    if age < 0:
        raise ValueError('Возраст не может быть отрицательным')
except ValueError as err:
    print('Поймали свою ошибку:', err)